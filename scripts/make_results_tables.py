#!/usr/bin/env python3
"""
Write docs/RESULTS_TABLES.md: the numeric results of the LLM panel as Markdown tables, generated from the files in
llm_panel/results/ and llm_panel/completeness/ so that the text and the data cannot drift apart.

Usage (from the repository root):   python scripts/make_results_tables.py [output.md]        Requires pandas, openpyxl.
"""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "llm_panel/results")
import sys
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs/RESULTS_TABLES.md")
MODELS = ["claude", "chatgpt", "deepseek", "gemini"]
NAMES = {"claude": "Claude Sonnet 5.5", "chatgpt": "ChatGPT (GPT-6)", "deepseek": "DeepSeek (DeepThink)", "gemini": "Gemini 3.1 Pro"}

def md(df, floatfmt=None):
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(lines)

def reading(a): return "reliable" if a >= 0.8 else "tentative" if a >= 0.667 else "not reliable"

def main():
    out = ["# Results tables (generated)\n",
           "Generated by `scripts/make_results_tables.py` from `llm_panel/results/`. Do not edit by hand.\n"]

    # 1 agreement among the models
    boot = pd.read_csv(os.path.join(ROOT, "llm_panel/figures/out/fig2_alpha_bootstrap.csv"))
    t = pd.DataFrame({"Field": boot.dim.str.replace("$\\tau$", "tau", regex=False),
                      "Metric": boot.metric,
                      "Krippendorff alpha": boot.alpha.map(lambda v: f"{v:.2f}"),
                      "95% bootstrap interval": [f"{lo:.2f} to {hi:.2f}" for lo, hi in zip(boot.lo, boot.hi)],
                      "Reading": boot.alpha.map(reading),
                      "Kendall W": boot.W.map(lambda v: "" if pd.isna(v) else f"{v:.2f}")})
    out += ["## 1. Agreement among the four models (55 threats)\n", md(t), "",
            "Reading: alpha >= 0.800 reliable, 0.667 to 0.800 tentative, below 0.667 not reliable (Krippendorff). "
            "Intervals: 1000 bootstrap resamples of the threats (seed 7). Tier is shown with the ordinal metric; "
            "its nominal alpha is 0.30. W is given for the score dimensions only.\n"]

    # 2 without Claude, leave-one-out
    av = pd.read_csv(os.path.join(RES, "agreement_alpha_vs_W.csv"))
    four = av[av.raters == "4 LLMs"].set_index("dimension"); three = av[av.raters == "3 LLMs (no Claude)"].set_index("dimension")
    five = av[av.raters == "4 LLMs + catalogue"].set_index("dimension")
    loo = pd.read_excel(os.path.join(RES, "Agreement_alpha_vs_W.xlsx"), sheet_name="Leave_one_out")
    rows = []
    for d in ["D (damage)", "R (reproducibility)", "E (exploitability)", "A (affected users)", "Di strong (discoverability)",
              "Di weak", "S strong (PA-DREAD total)", "S weak"]:
        l = loo[loo.dimension == d].alpha_interval
        rows.append({"Dimension": d, "alpha, 4 LLMs": f"{four.loc[d, 'alpha_interval']:.3f}",
                     "alpha, without Claude": f"{three.loc[d, 'alpha_interval']:.3f}",
                     "alpha, leave-one-out range": f"{l.min():.3f} to {l.max():.3f}",
                     "alpha, 4 LLMs + catalogue": f"{five.loc[d, 'alpha_interval']:.3f}",
                     "W, 4 LLMs": f"{four.loc[d, 'W']:.3f}"})
    out += ["## 2. Self-preference and leave-one-out checks (scores, interval alpha)\n", md(pd.DataFrame(rows)), "",
            "Models can favour output of their own family, so the panel is also analysed without Claude "
            "and with each model left out in turn. The catalogue is added as a fifth rater in the last alpha column.\n"]

    # 3 model vs catalogue
    mv = pd.read_csv(os.path.join(RES, "model_vs_catalogue.csv")).set_index("model").loc[MODELS]
    pct = lambda s: (s * 100).round(0).astype(int).astype(str) + "%"
    t = pd.DataFrame({"Measure": ["Layer exact", "STRIDE-tau primary exact", "Tier exact", "Evidence level exact", "Enabler flag exact",
                                  "D within 1", "R within 1", "E within 1", "A within 1", "Di strong within 1", "Di weak within 1",
                                  "Band (strong pass) exact", "Spearman rho of total score (strong)", "Share of threats judged valid"]})
    cols = ["layer exact match", "stride_primary exact match", "tier exact match", "evidence exact match", "is_enabler exact match",
            "D within +-1", "R within +-1", "E within +-1", "A within +-1", "Di_strong within +-1", "Di_weak within +-1",
            "band_strong exact match"]
    for m in MODELS:
        vals = [f"{mv.loc[m, c] * 100:.0f}%" for c in cols] + [f"{mv.loc[m, 'S_strong Spearman vs catalogue']:.2f}", f"{mv.loc[m, 'share valid'] * 100:.0f}%"]
        t[NAMES[m]] = vals
    out += ["## 3. Each model against the catalogue\n", md(t), ""]

    # 4 retest
    rt = pd.read_csv(os.path.join(RES, "retest_chatgpt_B3_run1_vs_run2.csv"))
    out += ["## 4. Test-retest: ChatGPT, prompt B3 (Layer 3, 12 threats), same prompt in a second fresh chat\n", md(rt), ""]

    # 5 verdicts and tags
    L = pd.read_csv(os.path.join(RES, "panel_long.csv")); S = pd.read_csv(os.path.join(RES, "panel_summary.csv"))
    v = L.validity.value_counts().rename_axis("Validity verdict").reset_index(name="Ratings (of 220)")
    tags = {}
    for f in ["layer", "stride_primary", "tier", "evidence", "is_enabler", "validity", "D", "R", "E", "A", "Di_strong", "Di_weak", "goals"]:
        tags[f] = S["tag_" + f].value_counts().to_dict()
    tg = pd.DataFrame(tags).T.fillna(0).astype(int)[["agree", "panel_vs_catalogue", "split"]].rename_axis("Field").reset_index()
    tot = tg[["agree", "panel_vs_catalogue", "split"]].sum()
    out += ["## 5. Validity verdicts and the disagreement tags\n", md(v), "",
            "Tags per field (one per threat). `agree`: the models (at least 2/3, or an interquartile range of at most 1 for scores) and the catalogue agree. "
            "`panel_vs_catalogue`: the models agree with each other but not with the catalogue. `split`: no consensus among the models.\n", md(tg), "",
            f"Total scored fields: {int(tot.sum())}: agree {int(tot['agree'])}, panel_vs_catalogue {int(tot['panel_vs_catalogue'])}, split {int(tot['split'])}.\n"]

    # 6 contested
    ci = pd.read_excel(os.path.join(RES, "Agreement_alpha_vs_W.xlsx"), sheet_name="Contested_items")
    ci = ci[ci.contested == True][["ID", "title", "S_claude", "S_chatgpt", "S_deepseek", "S_gemini", "S_catalogue", "S_range"]]
    out += ["## 6. Contested threats (rule in `llm_panel/tools/agreement.py`)\n", md(ci.assign(**{c: ci[c].map(lambda v: "" if pd.isna(v) else int(v)) for c in ["S_claude","S_chatgpt","S_deepseek","S_gemini","S_catalogue","S_range"]})), "",
            "Total score S (strong pass) by model and in the catalogue; empty where a model treated the record as an enabler.\n"]

    # 7 completeness
    em = pd.read_csv(os.path.join(ROOT, "llm_panel/completeness/elicitation_mapping_manual.csv"))
    first = em.drop_duplicates("k")
    per = first.groupby("model").map_class.value_counts().unstack().fillna(0).astype(int).reindex(MODELS)
    per["listed"] = per.sum(axis=1)
    x = em[em.map_class.isin(["C", "P"]) & em.catalogue_id.notna()]
    per["catalogue threats named (of 55)"] = [x[x.model == m].catalogue_id.nunique() for m in MODELS]
    per.index = [NAMES[m] for m in MODELS]
    per = per.rename(columns={"C": "matches a catalogue threat", "P": "related", "N": "no counterpart"}).rename_axis("Model").reset_index()
    nm = x.groupby("catalogue_id").model.nunique()
    named_none = sorted(set(S.id) - set(nm.index))
    out += ["## 7. Completeness: what the models listed unprompted (Prompt A)\n", md(per), "",
            f"All models together listed {first.shape[0]} threats: {int((first.map_class == 'C').sum())} match a catalogue threat, "
            f"{int((first.map_class == 'P').sum())} are related and {int((first.map_class == 'N').sum())} have no counterpart. "
            f"{nm.shape[0]} of 55 catalogue threats are named by at least one model, {int((nm >= 2).sum())} by two or more, "
            f"{int((nm >= 3).sum())} by three or more and {int((nm == 4).sum())} by all four. Named by none: {', '.join(named_none)}.\n",
            "The mapping of the 143 listed threats to the catalogue is a single-analyst judgement "
            "(`llm_panel/completeness/elicitation_mapping_manual.csv`) and has not been checked by a second coder.\n"]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", OUT)

if __name__ == "__main__":
    main()
